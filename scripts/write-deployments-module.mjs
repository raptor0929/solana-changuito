/**
 * deployments.json -> apps/web/lib/deployments.ts
 *
 * deployments.json is written by scripts/solana-init.mts after the escrow is
 * deployed and initialized on devnet. The generated module is committed so a
 * fresh clone builds without a deploy.
 *
 * The app runs on one cluster. The NetworkId type, NETWORK_IDS and the
 * narrowing helpers survive with a single member because a dozen modules
 * thread a network through and there is no reason to churn them; every unknown
 * value lands on devnet, which cannot spend real money.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const d = JSON.parse(readFileSync(join(root, 'deployments.json'), 'utf8'));
if (d.cluster !== 'devnet') throw new Error(`deployments.json: expected cluster devnet, got ${d.cluster}`);

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "\\'")}'`);

const out = `// GENERATED by scripts/write-deployments-module.mjs — do not edit.
// Source of truth: deployments.json at the repo root, written by
// scripts/solana-init.mts.

export type NetworkId = 'devnet';

export const NETWORK_IDS = ['devnet'] as const;

export const DEFAULT_NETWORK: NetworkId = 'devnet';

export const DEPLOYMENTS = {
  devnet: {
    id: 'devnet',
    rpcUrl: ${q(d.rpcUrl)},
    deployedAt: ${q(d.deployedAt)},
    /** anchor/programs/changuito_escrow. */
    programId: ${q(d.programId)},
    /** The escrow's Config PDA: resolver, treasury and mint. */
    config: ${q(d.config)},
    /** Our devnet USDC. The resolver is its mint authority (the faucet). */
    usdcMint: ${q(d.usdcMint)},
    usdcDecimals: ${Number(d.usdcDecimals)},
    usdcCode: 'USDC',
    /** Backend hot key: signs settle, refund and faucet mints. */
    resolver: ${q(d.resolver)},
    /** Where a settled order's USDC ends up. The app never signs for it. */
    treasury: ${q(d.treasury)},
    treasuryToken: ${q(d.treasuryToken)},
  },
} as const;

/** Signatures that prove the deployment: deploy, initialize, smoke settle/refund. */
export const EVIDENCE = ${JSON.stringify(d.evidence ?? {}, null, 2)} as const;

export type Deployment = (typeof DEPLOYMENTS)[NetworkId];

/** Narrows an untrusted string — a query param, localStorage — to a network. */
export function asNetwork(value: unknown): NetworkId | null {
  return typeof value === 'string' && (NETWORK_IDS as readonly string[]).includes(value)
    ? (value as NetworkId)
    : null;
}

/** Same, but never fails: anything unrecognised becomes the default. */
export function networkOrDefault(value: unknown): NetworkId {
  return asNetwork(value) ?? DEFAULT_NETWORK;
}

/** True once the program and accounts for this network actually exist. */
export function isConfigured(net: NetworkId): boolean {
  const d = DEPLOYMENTS[net];
  return Boolean(d.programId && d.usdcMint && d.resolver && d.treasury);
}

export function deployment(net: NetworkId = DEFAULT_NETWORK): Deployment {
  if (!isConfigured(net)) {
    throw new Error(\`El programa no está desplegado en \${net}. Corré scripts/solana-init.mts.\`);
  }
  return DEPLOYMENTS[net];
}
`;

writeFileSync(join(root, 'apps/web/lib/deployments.ts'), out);
console.log('  wrote apps/web/lib/deployments.ts');
